export function getCountryData(countryCode) {
  return COST_DATA[countryCode] || null;
}

export function convertPrice(priceUSD, exchangeRates, targetCurrency) {
  if (!exchangeRates || !priceUSD) return null;
  const rate = exchangeRates[targetCurrency];
  if (!rate) return priceUSD;
  return priceUSD * rate;
}

export function formatPrice(amount, currency) {
  if (amount === null || amount === undefined) return 'N/A';

  const symbols = {
    USD: '$', EUR: '€', GBP: '£', INR: '₹', JPY: '¥',
    CZK: 'Kč', PLN: 'zł', HUF: 'Ft', UAH: '₴', RON: 'lei',
    TRY: '₺', BRL: 'R$', KRW: '₩', CAD: 'CA$', AUD: 'A$',
    CHF: 'Fr', SEK: 'kr', NOK: 'kr', DKK: 'kr', PKR: '₨',
  };

  const symbol = symbols[currency] || currency + ' ';
  const decimals = ['JPY', 'KRW', 'HUF'].includes(currency) ? 0 : 2;

  return `${symbol}${amount.toLocaleString('en-US', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  })}`;
}
